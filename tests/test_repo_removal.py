"""Removing a repository: which .repo files the GUI offers and the helper agrees to delete."""
import pytest

from kram.core.repo_files import REPO_DIR, Removal, removal
from kram.helper import kram_helper as helper


@pytest.mark.parametrize(("path", "owner", "expected"), [
    ("/etc/yum.repos.d/vscode.repo", None, Removal.ALLOWED),
    ("/etc/yum.repos.d/google-chrome.repo", "fedora-workstation-repositories", Removal.OWNED),
    ("/usr/share/dnf5/repos.d/fedora.repo", "fedora-repos", Removal.OWNED),
    ("/usr/share/dnf5/repos.d/local.repo", None, Removal.SYSTEM),
    ("/etc/distro.repos.d/x.repo", None, Removal.SYSTEM),
    ("/etc/yum.repos.d/sub/x.repo", None, Removal.SYSTEM),
    ("/etc/yum.repos.d/x.conf", None, Removal.SYSTEM),
    ("", None, Removal.NO_FILE),
])
def test_what_the_gui_offers(path, owner, expected):
    assert removal(path, owner) is expected


def test_the_gui_and_the_helper_agree_on_the_folder():
    assert REPO_DIR == helper.REPO_DIR


@pytest.fixture
def repo_dir(tmp_path):
    (tmp_path / "vscode.repo").write_text("[code]\n")
    (tmp_path / "insync.repo").write_text("[insync]\n[insync-source]\n")
    (tmp_path / "chrome.repo").write_text("[google-chrome]\n")
    (tmp_path / "link.repo").symlink_to(tmp_path / "vscode.repo")
    return tmp_path


def files_for(repo_dir, requested, extra=None, owners=None):
    configured = {"code": f"{repo_dir}/vscode.repo", "insync": f"{repo_dir}/insync.repo",
                  "insync-source": f"{repo_dir}/insync.repo", "google-chrome": f"{repo_dir}/chrome.repo",
                  "link": f"{repo_dir}/link.repo", "fedora": "/usr/share/dnf5/repos.d/fedora.repo",
                  **(extra or {})}
    return helper.repo_files_to_remove(set(requested), configured, (owners or {}).get, str(repo_dir))


def test_the_helper_deletes_whole_files_of_the_users_own(repo_dir):
    assert files_for(repo_dir, ["code"]) == [f"{repo_dir}/vscode.repo"]
    assert files_for(repo_dir, ["insync", "insync-source", "code"]) == [f"{repo_dir}/insync.repo",
                                                                         f"{repo_dir}/vscode.repo"]


@pytest.mark.parametrize(("requested", "extra", "owners", "error"), [
    (["insync"], None, None, "also configures insync-source"),
    (["google-chrome"], None, {"chrome.repo": "fedora-workstation-repositories"}, "belongs to the package"),
    (["fedora"], None, None, "is not a file in"),
    (["link"], None, None, "not a regular file"),
    (["nope"], None, None, "not configured: nope"),
    (["dots"], {"dots": "{dir}/../x.repo"}, None, "is not a file in"),
    (["conf"], {"conf": "{dir}/x.conf"}, None, "is not a file in"),
    (["gone"], {"gone": "{dir}/gone.repo"}, None, "gone.repo"),
    (["nofile"], {"nofile": ""}, None, "no file is not a file in"),
])
def test_the_helper_refuses(repo_dir, requested, extra, owners, error):
    extra = {k: v.format(dir=repo_dir) for k, v in (extra or {}).items()}
    owners = {f"{repo_dir}/{k}": v for k, v in (owners or {}).items()}
    with pytest.raises(helper.ProtocolError, match=error):
        files_for(repo_dir, requested, extra, owners)


def test_overrides_of_the_removed_repositories(tmp_path):
    path = tmp_path / "99-config_manager.repo"
    path.write_text("# Generated by libdnf5.\n[google-chrome]\nenabled=1\n[insync]\nenabled=0\nPriority=5\n"
                    "[code]\nenabled=0\n")
    assert helper.overridden_options({"insync", "code", "other"}, str(path)) == ["insync.enabled", "insync.Priority",
                                                                                  "code.enabled"]
    assert helper.overridden_options({"insync"}, str(tmp_path / "missing.repo")) == []
    path.write_text("not an ini file")
    assert helper.overridden_options({"insync"}, str(path)) == []
